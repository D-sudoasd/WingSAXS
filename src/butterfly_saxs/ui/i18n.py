CATALOGS = {"en": _EN, "zh_CN": _ZH}


def validate_language(language: Any) -> str:
    """Return a supported language code or fail with a focused error."""

    value = str(language)
    if value not in SUPPORTED_LANGUAGES:
        choices = ", ".join(SUPPORTED_LANGUAGES)
        raise ValueError(f"unsupported UI language {value!r}; expected one of: {choices}")
    return value


def translate(language: Any, key: str, **values: Any) -> str:
    """Translate one known UI key and apply explicit format values."""

    code = validate_language(language)
    template = CATALOGS[code][key]
    return template.format(**values)


